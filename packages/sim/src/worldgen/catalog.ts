/**
 * Worldgen catalog: species biology, territories, and links for `createWorld`.
 *
 * Species ids, slugs, and display names come from `@boing-pets/contract`
 * (`SPECIES_CATALOG`) so the kernel and the client use one name per species.
 * Ids 1–3 and territories 1–3 keep their original ids, numbers, and founder
 * order, so the first 12 founders of every seed are unchanged by the
 * expansion. New species and territories append after them.
 */
import {
  SPECIES_CATALOG,
  type Diet,
  type SpeciesGait,
  type SpeciesSlug,
} from "@boing-pets/contract";

export type SpeciesBiology = {
  slug: SpeciesSlug;
  maturityDays: number;
  baseLifespanDays: number;
  gestationDays: number;
  juvenileDays: number;
  baseCuriosity: number;
  baseAggression: number;
  baseLoyalty: number;
  baseSociability: number;
  baseBravery: number;
  baseRiskTaking: number;
  colorHex: string;
  /** Per-tick offsets added to the ruleset's hunger / thirst / fatigue drift. */
  needs: { hunger: number; thirst: number; fatigue: number };
  /** Per-mille added to the forage success chance (skill at finding food). */
  forageSkill: number;
  /** Founder gene centres (0–1000); founders roll ± `worldgenGeneSpread`. */
  genes: {
    strength: number;
    speed: number;
    intelligence: number;
    curiosity: number;
    sociability: number;
  };
  /** Territories besides home the species is at ease in. */
  habitat: readonly TerritorySlug[];
};

export type SpeciesCatalogRow = SpeciesBiology & {
  id: number;
  displayName: string;
  home: TerritorySlug;
  diet: Diet;
  gait: SpeciesGait;
};

